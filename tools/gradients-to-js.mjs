// tools/gradients-to-js.mjs — turns the output of tools/wolfram/export-gradients.wls (Mathematica's ColorData["Gradients"],
// 65 RGB samples each) into demos/voronoi-diagrams/gradients.js, the data module of the "color scheme" menu.
//   node tools/gradients-to-js.mjs [tests/golden/voronoi-diagrams.gradients.json]   (writes the module)
//   node tools/gradients-to-js.mjs --check [json]                                   (exit 1 if the module differs)
// The menu keeps Mathematica's order; samples are stored as RGB 0 … 255 with two decimals (an error below 0.005/255).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'demos/voronoi-diagrams/gradients.js');

/** The module text for the exported data { version, gradients: [{ name, samples: [[r, g, b] 0 … 1] }] }. */
export function gradientsModule(data) {
  const n = (v) => String(Math.round(v * 25500) / 100);
  const rows = data.gradients.map((g) => {
    const k = g.samples.length - 1;
    const s = g.samples.map((c, i) => `[${Math.round((i / k) * 1e6) / 1e6},[${c.map(n).join(',')}]]`);
    return `  ${JSON.stringify(g.name)}: { source: 'Mathematica', samples: [${s.join(',')}] },`;
  });
  return `// SPDX-FileCopyrightText: 2026 Tico Hannan
// SPDX-FileCopyrightText: Original Wolfram Demonstration by Ed Pegg Jr, Jeff Bryant and Theodore W. Gray
// SPDX-License-Identifier: CC-BY-NC-SA-3.0
// demos/voronoi-diagrams/gradients.js — GENERATED by tools/gradients-to-js.mjs from tests/golden/voronoi-diagrams.gradients.json
// (do not edit by hand). The colour gradients of the "color scheme" menu, the original's ColorData["Gradients"]: the
// ${data.gradients.length} gradients of ${data.version}, exported by the owner with tools/wolfram/export-gradients.wls (v0.1.36;
// before, D-VD-04: five measured on the snapshots). Each: ${data.gradients[0].samples.length} samples (x in 0 … 1, RGB 0 … 255), read linearly between
// samples; against the colours measured on the five snapshots the reading differs by at most 3/255.
export const GRADIENTS = Object.freeze({
${rows.join('\n')}
});
export const GRADIENT_NAMES = Object.freeze(Object.keys(GRADIENTS));
/** ColorData[name][x] as RGB 0 … 1: linear between the two samples around x (clamped to 0 … 1). */
export function gradientColor(name, x) {
  const s = GRADIENTS[name].samples, t = Math.min(1, Math.max(0, x));
  let i = 0;
  while (i + 2 < s.length && s[i + 1][0] < t) i++;
  const [x0, c0] = s[i], [x1, c1] = s[Math.min(i + 1, s.length - 1)];
  const f = x1 > x0 ? Math.min(1, Math.max(0, (t - x0) / (x1 - x0))) : 0;
  return c0.map((v, j) => (v + (c1[j] - v) * f) / 255);
}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const args = process.argv.slice(2), check = args.includes('--check');
  const src = args.find((a) => !a.startsWith('--')) ?? path.join(root, 'tests/golden/voronoi-diagrams.gradients.json');
  const text = gradientsModule(JSON.parse(fs.readFileSync(src, 'utf8')));
  if (check) {
    const same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8') === text;
    console.log(same ? 'gradients.js is up to date.' : 'gradients.js differs from the exported data: run node tools/gradients-to-js.mjs');
    process.exit(same ? 0 : 1);
  }
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(root, OUT)}: ${JSON.parse(fs.readFileSync(src, 'utf8')).gradients.length} gradients`);
}
