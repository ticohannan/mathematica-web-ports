const kindOf = (rel) => {
  const ext = posix.extname(rel).toLowerCase();
  if (ext === '.js' || ext === '.mjs') return 'js';
  if (ext === '.css') return 'css';
  if (ext === '.html' || ext === '.htm') return 'html';
  return 'file';
};

/**
 * Collect every file that the given HTML entry pages load, recursively.
 * @param {string} root      folder that holds the site (the repository)
 * @param {string[]} entries repository-relative paths of the HTML pages (POSIX separators)
 * @param {object} [opts]    { extraFiles: [], dynamicImportsIn: [], rootPage: 'index.html' (links to it are allowed
 *                           and served by the generated page) }
 * @returns {{ files: string[], errors: string[], warnings: string[], external: string[], rootLinks: string[] }}
 */
export function collect(root, entries, opts = {}) {
  const rootPage = opts.rootPage ?? 'index.html';
  const dynamicOk = new Set(opts.dynamicImportsIn || []);
  const files = new Set();
  const errors = [], warnings = [], external = new Set(), rootLinks = new Set();
  const scanCache = new Map();
  const visited = new Set();
  const queue = [];
  const dirCache = new Map();
  const listDir = (d) => { if (!dirCache.has(d)) { try { dirCache.set(d, new Set(fs.readdirSync(path.join(root, d)))); } catch { dirCache.set(d, null); } } return dirCache.get(d); };
  /** 'file' | 'dir' | 'missing' | 'case:<actual>' (exact letter case checked segment by segment) */
  const stat = (rel) => {
    const parts = rel.split('/');
    let cur = '';
    for (const p of parts) {
      const list = listDir(cur || '.');
      if (!list) return 'missing';
      if (!list.has(p)) {
        const alt = [...list].find((x) => x.toLowerCase() === p.toLowerCase());
        return alt ? `case:${cur ? cur + '/' : ''}${alt}` : 'missing';
      }
      cur = cur ? `${cur}/${p}` : p;
    }
    return fs.statSync(path.join(root, rel)).isDirectory() ? 'dir' : 'file';
  };
  const where = (from, line) => `${from}${line ? `:${line}` : ''}`;

  /** Resolve a URL-like reference against the repository-relative file `from`; returns a path, or null to skip. */
  const resolvePath = (from, spec, line, ctx) => {
    const s = spec.trim();
    if (!s || s.startsWith('#') || s.startsWith('?')) return null;
    if (/^(data|blob|javascript|mailto|tel|about):/i.test(s)) return null;
    if (/^([a-z][a-z0-9+.-]*:)?\/\//i.test(s) || /^[a-z][a-z0-9+.-]*:/i.test(s)) {
      if (ctx === 'link') return null; // an ordinary hyperlink to another site
      if (ctx === 'import') errors.push(`${where(from, line)}: remote module "${s}" (the bundle must not load code from elsewhere)`);
      else external.add(`${where(from, line)}: ${s}`);
      return null;
    }
    let p = s.replace(/[?#].*$/, '');
    try { p = decodeURIComponent(p); } catch { /* keep as is */ }
    if (p.startsWith('/')) { errors.push(`${where(from, line)}: root-absolute path "${s}" (use a relative path; the app must work in any folder)`); return null; }
    const joined = posix.normalize(posix.join(posix.dirname(from), p));
    if (joined === '..' || joined.startsWith('../')) { errors.push(`${where(from, line)}: "${s}" points outside the site folder`); return null; }
    const rel = joined === '.' ? '' : joined.replace(/\/$/, '');
    if (PRIVATE.some((q) => (rel + '/').startsWith(q))) { errors.push(`${where(from, line)}: "${s}" points into a private folder (${rel})`); return null; }
    return { rel, dirLike: p.endsWith('/') || p === '' || p === '.' };
  };

  const add = (rel, from, line, how, doc, importMap) => {
    let st = stat(rel || '.');
    if (st === 'dir' && (how === 'html' || how === 'link')) { rel = rel ? `${rel}/index.html` : 'index.html'; st = stat(rel); }
    if (st === 'missing' || st === 'dir') { errors.push(`${where(from, line)}: cannot resolve "${rel}" (${st === 'dir' ? 'a folder' : 'no such file'})`); return; }
    if (st.startsWith('case:')) { errors.push(`${where(from, line)}: "${rel}" differs in letter case from the file "${st.slice(5)}" (fails on case-sensitive servers)`); return; }
    files.add(rel);
    const k = kindOf(rel);
    const key = k === 'js' ? `${rel}|${doc}` : rel;
    if ((k === 'js' || k === 'css' || k === 'html') && !visited.has(key)) { visited.add(key); queue.push({ rel, kind: k, doc, importMap }); }
  };

  const resolveModule = (from, spec, line, doc, importMap) => {
    if (/^(\.{0,2}\/|[a-z][a-z0-9+.-]*:)/i.test(spec)) return resolvePath(from, spec, line, 'import');
    const map = importMap?.imports || {};
    let target = null;
    if (Object.hasOwn(map, spec)) target = map[spec];
    else {
      const key = Object.keys(map).filter((k2) => k2.endsWith('/') && spec.startsWith(k2)).sort((a, b) => b.length - a.length)[0];
      if (key) target = map[key] + spec.slice(key.length);
    }
    if (target === null) { errors.push(`${where(from, line)}: bare module name "${spec}" is not in the import map of ${doc}`); return null; }
    return resolvePath(doc, target, importMap.line, 'import');
  };

  const handleJs = (rel, src, doc, importMap, lineOffset = 0) => {
    for (const r of scanJs(src)) {
      const line = r.line + lineOffset;
      if (!r.literal) {
        if (r.unreadable) errors.push(`${where(rel, line)}: cannot read this import statement: ${r.spec}`);
        else if (r.warnOnly) warnings.push(`${where(rel, line)}: not followed (path computed at run time): ${r.spec}`);
        else if (dynamicOk.has(rel)) warnings.push(`${where(rel, line)}: non-literal reference covered by "extraFiles": ${r.spec}`);
        else errors.push(`${where(rel, line)}: non-literal ${r.kind === 'import' ? 'dynamic import' : 'module-relative URL'} ${r.spec} — list the files it can load in tools/bundle-app.config.json ("extraFiles") and this file in "dynamicImportsIn"`);
        continue;
      }
      let res;
      if (r.kind === 'import' || (r.base === 'module' && r.resolve)) res = resolveModule(rel, r.spec, line, doc, importMap);
      else res = resolvePath(r.base === 'document' ? doc : rel, r.spec, line, r.kind === 'import' ? 'import' : 'asset');
      if (!res) continue;
      const how = r.kind === 'import' && r.attrType && r.attrType !== 'javascript' ? 'file' : r.kind;
      if (how === 'file' && kindOf(res.rel) === 'js') { files.add(res.rel); continue; } // e.g. a JSON module named .js: copy, do not scan
      add(res.rel, rel, line, how, doc, importMap);
    }
  };
  const handleCss = (rel, src, lineOffset = 0, doc = rel) => {
    for (const r of scanCss(src)) {
      const res = resolvePath(rel, r.spec, r.line + lineOffset, 'asset');
      if (res) add(res.rel, rel, r.line + lineOffset, 'css', doc, null);
    }
  };
  const handleHtml = (rel, src) => {
    const { refs, importMap: im, inlineJs, inlineCss } = scanHtml(src);
    let importMap = { imports: {}, line: 0 };
    if (im) {
      try {
        const j = JSON.parse(im.json);
        if (j.scopes && Object.keys(j.scopes).length) errors.push(`${where(rel, im.line)}: import-map "scopes" are not supported by the bundler`);
        importMap = { imports: j.imports || {}, line: im.line };
      } catch (e) { errors.push(`${where(rel, im.line)}: the import map is not valid JSON (${e.message})`); }
      for (const v of Object.values(importMap.imports)) { // mapped files must exist even if no module uses them yet
        const res = resolvePath(rel, v, im.line, 'import');
        if (res && !res.dirLike && stat(res.rel) !== 'file') errors.push(`${where(rel, im.line)}: import-map target "${v}" does not exist`);
      }
    }
    for (const r of refs) {
      if (r.as === 'base') { errors.push(`${where(rel, r.line)}: <base href> is not supported by the bundler`); continue; }
      if (r.as === 'importmap-src') { errors.push(`${where(rel, r.line)}: external import maps are not supported by browsers or the bundler`); continue; }
      const res = resolvePath(rel, r.spec, r.line, r.as === 'link' ? 'link' : r.as === 'script' ? 'import' : 'asset');
      if (!res) continue;
      if (r.as === 'link') {
        const target = res.dirLike || stat(res.rel || '.') === 'dir' ? (res.rel ? `${res.rel}/index.html` : 'index.html') : res.rel;
        if (target === rootPage) { rootLinks.add(`${where(rel, r.line)}: ${r.spec}`); continue; }
        if (entries.includes(target)) continue;
        add(target, rel, r.line, kindOf(target) === 'html' ? 'html' : 'link', target, null);
        continue;
      }
      add(res.rel, rel, r.line, r.as, rel, importMap);
    }
    for (const s of inlineJs) handleJs(rel, s.src, rel, importMap, s.line - 1);
    for (const s of inlineCss) handleCss(rel, s.src, s.line - 1);
  };

  for (const e of entries) add(e, '(entry)', 0, 'html', e, null);
  for (const x of opts.extraFiles || []) add(x, 'tools/bundle-app.config.json', 0, 'file', entries[0], null);
  while (queue.length) {
    const { rel, kind, doc, importMap } = queue.shift();
    let src = scanCache.get(rel);
    if (src === undefined) { src = fs.readFileSync(path.join(root, rel), 'utf8'); scanCache.set(rel, src); }
    if (kind === 'html') handleHtml(rel, src);
    else if (kind === 'css') handleCss(rel, src);
    else handleJs(rel, src, doc, importMap || { imports: {}, line: 0 });
  }
  return { files: [...files].sort(), errors: [...new Set(errors)], warnings: [...new Set(warnings)], external: [...external], rootLinks: [...rootLinks] };
}

