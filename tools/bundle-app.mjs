/** References in CSS: [{ spec, line, kind: 'import'|'url' }]. */
export function scanCss(src) {
  const clean = src.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '));
  const refs = [];
  const lineAt = (idx) => clean.slice(0, idx).split('\n').length;
  const seen = new Set();
  for (const m of clean.matchAll(/@import\s+(?:url\(\s*)?(["']?)([^"')\s;]+)\1/g)) {
    refs.push({ spec: m[2], line: lineAt(m.index), kind: 'import' });
    seen.add(m.index);
  }
  for (const m of clean.matchAll(/url\(\s*(["']?)([^"')]*?)\1\s*\)/g)) {
    if ([...seen].some((s) => m.index > s && m.index < s + 12)) continue; // @import url(…) already counted
    refs.push({ spec: m[2].trim(), line: lineAt(m.index), kind: 'url' });
  }
  return refs;
}

const decodeEntities = (s) => s.replace(/&(amp|lt|gt|quot|apos|#39|#x27);/g, (m, e) => ({ amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", '#39': "'", '#x27': "'" })[e]);

/** Tags of an HTML document: [{ name, attrs: Map, line, content? }] (content for script and style). */
export function parseHtmlTags(src) {
  const tags = [];
  const n = src.length;
  let i = 0;
  const lineAt = (idx) => { let l = 1; for (let k = 0; k < idx; k++) if (src.charCodeAt(k) === 10) l++; return l; };
  while (i < n) {
    const lt = src.indexOf('<', i);
    if (lt < 0) break;
    if (src.startsWith('<!--', lt)) { const e = src.indexOf('-->', lt + 4); i = e < 0 ? n : e + 3; continue; }
    if (!/[A-Za-z]/.test(src[lt + 1] ?? '')) { i = lt + 1; continue; }
    let j = lt + 1;
    while (j < n && /[A-Za-z0-9:-]/.test(src[j])) j++;
    const name = src.slice(lt + 1, j).toLowerCase();
    const attrs = new Map();
    while (j < n) {
      while (j < n && /\s/.test(src[j])) j++;
      if (src[j] === '>' || (src[j] === '/' && src[j + 1] === '>')) break;
      let a = j;
      while (j < n && !/[\s=>]/.test(src[j]) && !(src[j] === '/' && src[j + 1] === '>')) j++;
      const an = src.slice(a, j).toLowerCase();
      while (j < n && /\s/.test(src[j])) j++;
      let value = '';
      if (src[j] === '=') {
        j++;
        while (j < n && /\s/.test(src[j])) j++;
        const q = src[j];
        if (q === '"' || q === "'") { const e = src.indexOf(q, j + 1); value = src.slice(j + 1, e < 0 ? n : e); j = e < 0 ? n : e + 1; }
        else { a = j; while (j < n && !/[\s>]/.test(src[j])) j++; value = src.slice(a, j); }
      }
      if (an) attrs.set(an, decodeEntities(value));
      if (j === a) j++;
    }
    const end = src.indexOf('>', j);
    const tag = { name, attrs, line: lineAt(lt) };
    i = end < 0 ? n : end + 1;
    if (name === 'script' || name === 'style') {
      const close = src.toLowerCase().indexOf(`</${name}`, i);
      tag.content = src.slice(i, close < 0 ? n : close);
      tag.contentLine = lineAt(i);
      i = close < 0 ? n : src.indexOf('>', close) + 1 || n;
    }
    tags.push(tag);
  }
  return tags;
}

const MEDIA_ATTRS = { img: ['src'], source: ['src'], video: ['src', 'poster'], audio: ['src'], track: ['src'], embed: ['src'],
  iframe: ['src'], input: ['src'], object: ['data'], script: ['src'], link: ['href'], image: ['href', 'xlink:href'], use: ['href', 'xlink:href'] };

/**
 * References in an HTML document. Returns { refs: [{ spec, line, as: 'script'|'module'|'css'|'html'|'file'|'link' }],
 * importMap, inlineJs: [{ src, line }], inlineCss: [{ src, line }] }.
 */
export function scanHtml(src) {
  const refs = [], inlineJs = [], inlineCss = [];
  let importMap = null;
  for (const tag of parseHtmlTags(src)) {
    const { name, attrs, line } = tag;
    if (name === 'base' && attrs.has('href')) refs.push({ spec: attrs.get('href'), line, as: 'base' });
    if (name === 'script') {
      const type = (attrs.get('type') || '').toLowerCase();
      if (type === 'importmap') {
        if (attrs.has('src')) refs.push({ spec: attrs.get('src'), line, as: 'importmap-src' });
        else importMap = { json: tag.content, line };
        continue;
      }
      const isJs = !type || type === 'module' || /javascript|ecmascript/.test(type);
      if (!isJs) continue;
      if (attrs.has('src')) refs.push({ spec: attrs.get('src'), line, as: 'script' });
      else if (tag.content.trim()) inlineJs.push({ src: tag.content, line: tag.contentLine });
      continue;
    }
    if (name === 'style') { inlineCss.push({ src: tag.content, line: tag.contentLine }); continue; }
    if (attrs.has('style')) inlineCss.push({ src: attrs.get('style'), line });
    if (name === 'a' || name === 'area') {
      if (attrs.has('href')) refs.push({ spec: attrs.get('href'), line, as: 'link' });
      continue;
    }
    if (name === 'link') {
      const rel = (attrs.get('rel') || '').toLowerCase().split(/\s+/);
      if (rel.includes('canonical') || rel.includes('alternate') || rel.includes('dns-prefetch') || rel.includes('preconnect')) continue;
      if (attrs.has('href')) refs.push({ spec: attrs.get('href'), line, as: rel.includes('stylesheet') ? 'css' : 'file' });
      if (attrs.has('imagesrcset')) for (const s of srcsetUrls(attrs.get('imagesrcset'))) refs.push({ spec: s, line, as: 'file' });
      continue;
    }
    for (const a of MEDIA_ATTRS[name] || []) if (attrs.has(a)) refs.push({ spec: attrs.get(a), line, as: name === 'iframe' ? 'html' : 'file' });
    if (attrs.has('srcset')) for (const s of srcsetUrls(attrs.get('srcset'))) refs.push({ spec: s, line, as: 'file' });
  }
  return { refs, importMap, inlineJs, inlineCss };
}
const srcsetUrls = (v) => v.split(',').map((p) => p.trim().split(/\s+/)[0]).filter(Boolean);

