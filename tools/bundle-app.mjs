//            --zip          also write <out>/<dir>.zip (the folder as one archive)
//            --list         print the files of each bundle
//            --verbose      also list the run-time paths that were not followed (e.g. fetch(url) inside three.js loaders)
//            --update-docs  rewrite the generated contents table in demos/<dir>/DESIGN.md §6.1 (no bundle is written)
//
// How it works: starting from demos/<dir>/index.html the collector follows every reference that the browser
// will load — <script src>, <link href>, <img src>/srcset and other media, local <a href> links, the import map,
// static `import … from` / `export … from`, `import('…')` with a literal path, `new URL('…', import.meta.url)`,
// `import.meta.resolve('…')`, `fetch('…')` and `new Worker('…')` with literal paths, CSS `url(…)` and `@import` —
// recursively, and copies the files to <out>/<dir>/ with the same relative layout as in the repository, so no
// path needs to be rewritten. JavaScript is read with a small tokenizer (comments, strings, template literals and
// regular expressions are recognised), so imports quoted in comments or strings are not followed.
// It fails (exit code 1, every problem listed) on a reference it cannot resolve: a missing file, wrong letter
// case, a bare module name not in the import map, a root-absolute path, a remote module, a path outside the
// repository or into a private folder, or a dynamic import / `new URL(…, import.meta.url)` whose path is not a
// literal. Files that cannot be found automatically can be listed per app in tools/bundle-app.config.json
// ("extraFiles"); files whose non-literal dynamic imports are covered by that list go into "dynamicImportsIn";
// licence notices that must travel with an app's code go into "notices" (with "why", shown in the README).
// Added to every bundle: a root index.html that opens the app once per browser tab (sessionStorage flag; the app's
// "All demos" link, ../../index.html, leads back to it and then finds a link to the app), the app's DESIGN.md, LICENSE.md, the LICENSES/<id>.txt texts for the SPDX identifiers of the
// copied files (from their headers, else from REUSE.toml), licence files found in the copied files' folders
// (e.g. vendor/three/LICENSE), a generated README.md and an empty .nojekyll (GitHub Pages serves files as they are).
