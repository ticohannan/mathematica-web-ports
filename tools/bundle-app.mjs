/** Minimal reader for this repository's REUSE.toml: [{ paths: RegExp[], precedence, ids: string[] }]. */
export function readReuseToml(text) {
  const out = [];
  let cur = null, pendingKey = null, buf = '';
  const finish = (key, raw) => {
    const json = raw.trim().replace(/,\s*\]$/, ']');
    let v;
    try { v = JSON.parse(json); } catch { return; }
    if (key === 'path') cur.paths = (Array.isArray(v) ? v : [v]).map(globToRegExp);
    else if (key === 'precedence') cur.precedence = v;
    else if (key === 'SPDX-License-Identifier') cur.ids = spdxIds(String(v));
  };
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.replace(/^\s*#.*$/, '');
    if (pendingKey) {
      buf += ' ' + line;
      if ((buf.match(/\[/g) || []).length <= (buf.match(/\]/g) || []).length) { finish(pendingKey, buf); pendingKey = null; }
      continue;
    }
    if (/^\s*\[\[annotations\]\]/.test(line)) { cur = { paths: [], precedence: 'closest', ids: [] }; out.push(cur); continue; }
    const m = line.match(/^\s*([A-Za-z-]+)\s*=\s*(.*)$/);
    if (!m || !cur) continue;
    const [, key, val] = m;
    if (val.trim().startsWith('[') && (val.match(/\[/g) || []).length > (val.match(/\]/g) || []).length) { pendingKey = key; buf = val; continue; }
    finish(key, val);
  }
  return out;
}
function globToRegExp(g) {
  let re = '';
  for (let i = 0; i < g.length; i++) {
    const c = g[i];
    if (c === '*' && g[i + 1] === '*') { re += '.*'; i++; if (g[i + 1] === '/') i++; }
    else if (c === '*') re += '[^/]*';
    else if (c === '?') re += '[^/]';
    else re += c.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp(`^${re}$`);
}
export const spdxIds = (expr) => expr.replace(/[()]/g, ' ').split(/\s+(?:AND|OR|WITH)\s+|\s+/).map((s) => s.trim()).filter((s) => s && !/^(AND|OR|WITH)$/.test(s));

/** SPDX licence identifiers of one file: its header, unless REUSE.toml overrides it; REUSE.toml when it has none. */
export function licenceIdsOf(root, rel, reuse) {
  const matching = reuse.filter((a) => a.paths.some((re) => re.test(rel)));
  const override = matching.filter((a) => a.precedence === 'override').pop();
  if (override) return override.ids;
  let head = '';
  try { head = fs.readFileSync(path.join(root, rel), 'utf8').split('\n').slice(0, 15).join('\n'); } catch { /* binary or missing */ }
  const ids = [...head.matchAll(/SPDX-License-Identifier:\s*([^\n*]+?)\s*(?:\*\/|-->|$)/gm)].flatMap((m) => spdxIds(m[1]));
  if (ids.length) return [...new Set(ids)];
  return matching.length ? matching[matching.length - 1].ids : [];
}

