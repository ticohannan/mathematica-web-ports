function main(argv) {
  const args = [...argv];
  const opt = (name) => { const i = args.indexOf(name); if (i < 0) return false; args.splice(i, 1); return true; };
  const val = (name) => { const i = args.indexOf(name); if (i < 0) return null; const v = args[i + 1]; args.splice(i, 2); return v; };
  if (opt('--help') || opt('-h') || !args.length) {
    console.log('Usage: node tools/bundle-app.mjs <dir>… | --all [--out DIR] [--zip] [--list] [--verbose] [--update-docs]');
    return args.length ? 0 : 1;
  }
  const all = opt('--all'), zip = opt('--zip'), list = opt('--list'), docs = opt('--update-docs'), verbose = opt('--verbose');
  const show = (p) => { const r = path.relative(process.cwd(), p); return r && !r.startsWith('..') && !path.isAbsolute(r) ? r : p; };
  const out = val('--out');
  const unknown = args.filter((a) => a.startsWith('-'));
  if (unknown.length) { console.error(`unknown option(s): ${unknown.join(' ')}`); return 1; }
  const dirs = all ? listApps(REPO_ROOT) : args;
  if (!dirs.length) { console.error('no app given'); return 1; }
  if (docs) { updateDocs(dirs, REPO_ROOT); return process.exitCode || 0; }
  const outDir = out ? path.resolve(out) : path.join(REPO_ROOT, 'dist');
  let failed = 0;
  for (const dir of dirs) {
    try {
      const r = bundleApp(dir, { outDir, zip });
      const counts = areaGroups(r).map(([a, f]) => `${a === 'app' ? 'app' : a} ${f.length}`).join(', ');
      console.log(`${show(r.folder)}${path.sep}  ${r.files.length} files, ${fmtBytes(r.bytes)}  (${counts}; added ${r.added.length + GENERATED_FILES.length})${r.zipFile ? `  + ${show(r.zipFile)}` : ''}`);
      if (list) for (const f of r.files) console.log(`    ${f}`);
      if (verbose) for (const w of r.warnings) console.log(`  note: ${w}`);
      else if (r.warnings.length) console.log(`  ${r.warnings.length} note(s) on run-time paths that were not followed (--verbose lists them)`);
      for (const e of r.external) console.log(`  external (not bundled): ${e}`);
    } catch (e) {
      failed++;
      console.error(`✘ ${e.message}`);
    }
  }
  if (failed) console.error(`\n${failed} app(s) could not be bundled.`);
  return failed ? 1 : 0;
}

