const BEFORE_EXPR = new Set(['return', 'typeof', 'instanceof', 'in', 'of', 'new', 'delete', 'void', 'throw', 'case',
  'do', 'else', 'yield', 'await', 'export', 'default', 'extends']);
const isIdStart = (c) => /[A-Za-z_$\u0080-￿\\]/.test(c);
const isIdPart = (c) => /[A-Za-z0-9_$\u0080-￿\\]/.test(c);
const SIMPLE_ESC = { n: '\n', r: '\r', t: '\t', b: '\b', f: '\f', v: '\v', 0: '\0' };

/** Tokens of a JavaScript source: { type: 'id'|'num'|'str'|'tpl'|'regex'|'punct', value, line, dynamic? }. */
export function tokenizeJs(src) {
  const toks = [];
  const n = src.length;
  const stack = []; // 'brace' | 'template'
  let i = 0, line = 1, last = null;
  const push = (t) => { toks.push(t); last = t; };
  const countLines = (a, b) => { for (let k = a; k < b; k++) if (src.charCodeAt(k) === 10) line++; };
  const regexAllowed = () => {
    if (!last) return true;
    if (last.type === 'id') return BEFORE_EXPR.has(last.value);
    if (last.type === 'punct') return !(last.value === ')' || last.value === ']' || last.value === '}');
    return false;
  };
  // Reads template characters from i (just after ` or after the } closing ${…}); returns at the closing ` or ${.
  const readTemplateChars = (tok) => {
    let value = '';
    while (i < n) {
      const c = src[i];
      if (c === '\\') { value += src[i + 1] ?? ''; countLines(i, i + 2); i += 2; continue; }
      if (c === '`') { i++; tok.value += value; return 'end'; }
      if (c === '$' && src[i + 1] === '{') { i += 2; tok.value += value; tok.dynamic = true; stack.push('template'); return 'subst'; }
      if (c === '\n') line++;
      value += c; i++;
    }
    tok.value += value;
    return 'eof';
  };
  if (src.startsWith('#!')) while (i < n && src[i] !== '\n') i++;
  while (i < n) {
    const c = src[i];
    if (c === '\n') { line++; i++; continue; }
    if (/\s/.test(c) || c === '﻿') { i++; continue; }
    if (c === '/' && src[i + 1] === '/') { while (i < n && src[i] !== '\n') i++; continue; }
    if (c === '/' && src[i + 1] === '*') {
      const j = src.indexOf('*/', i + 2);
      const end = j < 0 ? n : j + 2;
      countLines(i, end); i = end; continue;
    }
    if (c === '"' || c === "'") {
      const startLine = line;
      let value = '';
      i++;
      while (i < n && src[i] !== c && src[i] !== '\n') {
        if (src[i] === '\\') {
          const e = src[i + 1] ?? '';
          if (e === '\n') line++;
          else if (e === '\r') { /* line continuation */ } else value += SIMPLE_ESC[e] ?? e;
          i += 2; continue;
        }
        value += src[i++];
      }
      i++;
      push({ type: 'str', value, line: startLine });
      continue;
    }
    if (c === '`') {
      const tok = { type: 'tpl', value: '', line, dynamic: false };
      i++;
      readTemplateChars(tok);
      push(tok);
      continue;
    }
    if (c === '}' && stack.length && stack[stack.length - 1] === 'template') {
      stack.pop();
      i++;
      const tok = { type: 'tpl', value: '', line, dynamic: true, continuation: true };
      readTemplateChars(tok);
      push(tok);
      continue;
    }
    if (c === '{') { stack.push('brace'); push({ type: 'punct', value: c, line }); i++; continue; }
    if (c === '}') { stack.pop(); push({ type: 'punct', value: c, line }); i++; continue; }
    if (isIdStart(c)) {
      let j = i + 1;
      while (j < n && isIdPart(src[j])) j++;
      push({ type: 'id', value: src.slice(i, j), line });
      i = j; continue;
    }
    if (/[0-9]/.test(c) || (c === '.' && /[0-9]/.test(src[i + 1] ?? ''))) {
      let j = i + 1;
      while (j < n && (/[0-9A-Za-z_.]/.test(src[j]) || ((src[j] === '+' || src[j] === '-') && /[eE]/.test(src[j - 1]) && !/^0[xX]/.test(src.slice(i, j))))) j++;
      push({ type: 'num', value: src.slice(i, j), line });
      i = j; continue;
    }
    if (c === '/' && regexAllowed()) {
      let j = i + 1, inClass = false, ok = false;
      while (j < n && src[j] !== '\n') {
        const d = src[j];
        if (d === '\\') { j += 2; continue; }
        if (d === '[') inClass = true;
        else if (d === ']') inClass = false;
        else if (d === '/' && !inClass) { ok = true; break; }
        j++;
      }
      if (ok) {
        j++;
        while (j < n && /[A-Za-z]/.test(src[j])) j++;
        push({ type: 'regex', value: src.slice(i, j), line });
        i = j; continue;
      }
    }
    push({ type: 'punct', value: c, line });
    i++;
  }
  return toks;
}

/**
 * References in a JavaScript source. Each: { kind, spec, line, literal, base, attrType? }
 *   kind 'import'  static import/export … from, side-effect import, or dynamic import() (dynamic: true)
 *   kind 'asset'   new URL('…', base), import.meta.resolve('…'), fetch('…'), new Worker('…')
 *   base 'module' (relative to this file; bare names go through the import map) or 'document' (relative to the page)
 *   literal false: the path is computed at run time (spec is the source text, for the message)
 */
export function scanJs(src) {
  const t = tokenizeJs(src);
  const refs = [];
  const P = (k, v) => t[k] !== undefined && t[k].type === 'punct' && t[k].value === v;
  const I = (k, v) => t[k] !== undefined && t[k].type === 'id' && (v === undefined || t[k].value === v);
  const lit = (k) => (t[k] && (t[k].type === 'str' || (t[k].type === 'tpl' && !t[k].dynamic)) ? t[k].value : null);
  const text = (a, b) => t.slice(a, b).map((x) => (x.type === 'str' ? JSON.stringify(x.value) : x.type === 'tpl' ? '`…`' : x.value)).join(' ');
  const matchClose = (k) => { // index of the token closing the bracket at k
    const open = t[k].value, close = { '(': ')', '{': '}', '[': ']' }[open];
    let depth = 0;
    for (let m = k; m < t.length; m++) {
      if (P(m, open)) depth++;
      else if (P(m, close) && --depth === 0) return m;
    }
    return t.length;
  };
  const attrType = (k) => { // import attributes: with { type: 'json' }
    if (!(I(k, 'with') || I(k, 'assert')) || !P(k + 1, '{')) return undefined;
    const e = matchClose(k + 1);
    for (let m = k + 2; m < e; m++) if ((I(m, 'type') || lit(m) === 'type') && P(m + 1, ':') && lit(m + 2) !== null) return lit(m + 2);
    return undefined;
  };
  const baseOf = (a, b) => { // tokens a..b-1 of the second argument of new URL(…)
    const s = text(a, b).replace(/\s+/g, '');
    if (s === 'import.meta.url') return 'module';
    if (/^(window\.|self\.|globalThis\.)?(document\.baseURI|document\.URL|location|location\.href)$/.test(s)) return 'document';
    return 'other';
  };
  for (let k = 0; k < t.length; k++) {
    const tok = t[k];
    if (tok.type !== 'id') continue;
    const afterDot = P(k - 1, '.');
    const line = tok.line;
    if (tok.value === 'import' && !afterDot) {
      if (P(k + 1, '(')) {
        const s = lit(k + 2);
        if (s !== null && (P(k + 3, ')') || P(k + 3, ','))) refs.push({ kind: 'import', dynamic: true, spec: s, line, literal: true, base: 'module' });
        else refs.push({ kind: 'import', dynamic: true, spec: `import(${text(k + 2, matchClose(k + 1))})`, line, literal: false, base: 'module' });
        continue;
      }
      if (P(k + 1, '.')) {
        if (I(k + 2, 'meta') && P(k + 3, '.') && I(k + 4, 'resolve') && P(k + 5, '(')) {
          const s = lit(k + 6);
          if (s !== null) refs.push({ kind: 'asset', spec: s, line, literal: true, base: 'module', resolve: true });
        }
        continue;
      }
      const s0 = lit(k + 1);
      if (s0 !== null) { refs.push({ kind: 'import', spec: s0, line, literal: true, base: 'module', attrType: attrType(k + 2) }); continue; }
      let depth = 0, found = -1;
      for (let m = k + 1; m < t.length && m < k + 20000; m++) {
        if (P(m, '{')) depth++;
        else if (P(m, '}')) depth--;
        else if (depth === 0 && (P(m, ';') || P(m, '(') || P(m, '='))) break;
        else if (depth === 0 && I(m, 'from') && lit(m + 1) !== null) { found = m + 1; break; }
      }
      if (found >= 0) refs.push({ kind: 'import', spec: lit(found), line, literal: true, base: 'module', attrType: attrType(found + 1) });
      else refs.push({ kind: 'import', spec: text(k, k + 6), line, literal: false, base: 'module', unreadable: true });
      continue;
    }
    if (tok.value === 'export' && !afterDot) {
      let m = -1;
      if (P(k + 1, '*')) { m = k + 2; if (I(m, 'as')) m += 2; }
      else if (P(k + 1, '{')) m = matchClose(k + 1) + 1;
      if (m >= 0 && I(m, 'from') && lit(m + 1) !== null) refs.push({ kind: 'import', spec: lit(m + 1), line, literal: true, base: 'module', attrType: attrType(m + 2) });
      continue;
    }
    if ((tok.value === 'URL' || tok.value === 'Worker' || tok.value === 'SharedWorker') && I(k - 1, 'new') && P(k + 1, '(')) {
      const close = matchClose(k + 1);
      let comma = -1, depth = 0;
      for (let m = k + 2; m < close; m++) {
        if (P(m, '(') || P(m, '[') || P(m, '{')) depth++;
        else if (P(m, ')') || P(m, ']') || P(m, '}')) depth--;
        else if (depth === 0 && P(m, ',')) { comma = m; break; }
      }
      const firstEnd = comma >= 0 ? comma : close;
      const s = firstEnd === k + 3 ? lit(k + 2) : null;
      if (tok.value === 'URL') {
        const base = comma >= 0 ? baseOf(comma + 1, close) : 'none';
        if (base === 'module' || base === 'document') {
          if (s !== null) refs.push({ kind: 'asset', spec: s, line, literal: true, base });
          else refs.push({ kind: 'asset', spec: `new URL(${text(k + 2, close)})`, line, literal: false, base });
        }
      } else if (s !== null) {
        refs.push({ kind: 'asset', spec: s, line, literal: true, base: 'document', worker: true });
      } else if (!(I(k + 2, 'new') && I(k + 3, 'URL'))) {
        refs.push({ kind: 'asset', spec: `new ${tok.value}(${text(k + 2, close)})`, line, literal: false, base: 'document', warnOnly: true });
      }
      continue;
    }
    if (tok.value === 'fetch' && P(k + 1, '(') && (!afterDot || I(k - 2, 'window') || I(k - 2, 'self') || I(k - 2, 'globalThis'))) {
      const s = lit(k + 2);
      if (s !== null && (P(k + 3, ')') || P(k + 3, ','))) refs.push({ kind: 'asset', spec: s, line, literal: true, base: 'document' });
      else refs.push({ kind: 'asset', spec: `fetch(${text(k + 2, matchClose(k + 1))})`, line, literal: false, base: 'document', warnOnly: true });
    }
  }
  return refs;
}

