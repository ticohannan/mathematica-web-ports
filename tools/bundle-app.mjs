/** Area of a repository-relative path within the bundle of app `dir`. */
export function areaOf(rel, dir) {
  if (rel.startsWith(`demos/${dir}/`)) return 'app';
  const m = rel.match(/^(demos\/[^/]+|shared|vendor\/[^/]+|vendor)\//);
  return m ? m[1] : posix.dirname(rel) === '.' ? '.' : rel.split('/')[0];
}

/** Plan one app's bundle (no files are written): loaded files, added files, licences, problems. */
export function planApp(dir, { root = REPO_ROOT, config = readConfig(root) } = {}) {
  const entry = `demos/${dir}/index.html`;
  if (!fs.existsSync(path.join(root, entry))) return { dir, errors: [`no such app: ${entry} does not exist`], warnings: [], loaded: [], added: [] };
  const cfg = config[dir] || {};
  const c = collect(root, [entry], { extraFiles: cfg.extraFiles, dynamicImportsIn: cfg.dynamicImportsIn });
  const reuseFile = path.join(root, 'REUSE.toml');
  const reuse = fs.existsSync(reuseFile) ? readReuseToml(fs.readFileSync(reuseFile, 'utf8')) : [];
  const ids = new Map(); // id → files
  for (const f of c.files) for (const id of licenceIdsOf(root, f, reuse)) { if (!ids.has(id)) ids.set(id, []); ids.get(id).push(f); }
  const errors = [...c.errors];
  const added = [];
  const addCopy = (rel) => { if (!c.files.includes(rel) && !added.includes(rel)) added.push(rel); };
  if (fs.existsSync(path.join(root, `demos/${dir}/DESIGN.md`))) addCopy(`demos/${dir}/DESIGN.md`);
  if (fs.existsSync(path.join(root, 'LICENSE.md'))) addCopy('LICENSE.md');
  for (const f of cfg.notices || []) {
    if (fs.existsSync(path.join(root, f))) addCopy(f);
    else errors.push(`tools/bundle-app.config.json: notice "${f}" of ${dir} does not exist`);
  }
  for (const id of [...ids.keys()].sort()) {
    const t = `LICENSES/${id}.txt`;
    if (fs.existsSync(path.join(root, t))) addCopy(t);
    else errors.push(`licence text ${t} for ${ids.get(id)[0]} not found`);
  }
  const unlicensed = c.files.filter((f) => !licenceIdsOf(root, f, reuse).length);
  for (const f of unlicensed) errors.push(`${f}: no SPDX-License-Identifier (header or REUSE.toml)`);
  for (const f of c.files) { // licence files in the folders of copied files (e.g. vendor/three/LICENSE)
    for (let d = posix.dirname(f); d !== '.' && d !== ''; d = posix.dirname(d)) {
      for (const name of LICENCE_FILE_NAMES) if (fs.existsSync(path.join(root, d, name))) addCopy(`${d}/${name}`);
    }
  }
  const html = fs.readFileSync(path.join(root, entry), 'utf8');
  const title = (html.match(/<title>([\s\S]*?)<\/title>/i)?.[1] ?? dir).trim();
  const creditsHtml = html.match(/<div class="credits"[^>]*>([\s\S]*?)<\/div>/i)?.[1] ?? '';
  const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
  return {
    dir, entry, title, creditsHtml, loaded: c.files, added: added.sort(), licences: ids, cfg,
    errors, warnings: c.warnings, external: c.external, rootLinks: c.rootLinks,
    needsWebgl2: parseHtmlTags(html).some((t) => t.name === 'script' && t.attrs.has('data-needs-webgl2')), usesThree: c.files.some((f) => f.startsWith('vendor/three/')),
    version: pkg.version, repoUrl: String(pkg.repository?.url || '').replace(/^git\+/, '').replace(/\.git$/, ''),
  };
}

const escapeHtml = (s) => s.replace(/&(?![a-z]+;|#\d+;)/gi, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const SPDX_NAMES = { 'CC-BY-NC-SA-3.0': 'CC BY-NC-SA 3.0', MIT: 'MIT' };
const htmlToMarkdown = (h) => decodeEntities(h.replace(/<a\s[^>]*href="([^"]*)"[^>]*>([\s\S]*?)<\/a>/gi, '[$2]($1)').replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim();
const fmtBytes = (b) => (b >= 1048576 ? `${(b / 1048576).toFixed(1)} MB` : `${Math.round(b / 1024)} KB`);
const AREA_LABEL = (a, dir) => (a === 'app' ? `the app (\`demos/${dir}/\`)` : `\`${a}/\``);

function areaGroups(plan) {
  const groups = new Map();
  for (const f of plan.loaded) {
    const a = areaOf(f, plan.dir);
    if (!groups.has(a)) groups.set(a, []);
    groups.get(a).push(f);
  }
  const order = (a) => (a === 'app' ? 0 : a === 'shared' ? 1 : a.startsWith('demos/') ? 2 : a.startsWith('vendor') ? 3 : 4);
  return [...groups.entries()].sort((x, y) => order(x[0]) - order(y[0]) || x[0].localeCompare(y[0]));
}
const GENERATED_FILES = ['index.html', 'README.md', '.nojekyll'];

/** The contents table for DESIGN.md §6.1 (generated; checked by tests/unit/bundle-app.test.js). */
export function contentsMarkdown(plan) {
  const rows = areaGroups(plan).map(([a, fs_]) => {
    const prefix = a === 'app' ? `demos/${plan.dir}/` : `${a}/`;
    return `| ${AREA_LABEL(a, plan.dir)} | ${fs_.length} | ${fs_.map((f) => `\`${f.startsWith(prefix) ? f.slice(prefix.length) : f}\``).join(', ')} |`;
  });
  const extra = [...GENERATED_FILES.map((f) => `\`${f}\``), ...plan.added.map((f) => `\`${f}\``)];
  return [
    '<!-- bundle-contents:begin (generated by `npm run bundle -- --update-docs`; do not edit by hand) -->',
    '| Area | Files | Files loaded by the page |',
    '|---|---|---|',
    ...rows,
    `| added by the bundler | ${extra.length} | ${extra.join(', ')} |`,
    '<!-- bundle-contents:end -->',
  ].join('\n');
}

function licenceLines(plan) {
  const lines = [];
  const rank = (a) => (a === 'app' ? 0 : a === 'shared' ? 1 : a.startsWith('demos/') ? 2 : a.startsWith('vendor') ? 3 : 4);
  for (const [id, files] of [...plan.licences.entries()].sort()) {
    const areas = [...new Set(files.map((f) => areaOf(f, plan.dir)))].sort((x, y) => rank(x) - rank(y) || x.localeCompare(y)).map((a) => AREA_LABEL(a, plan.dir));
    lines.push(`- **${SPDX_NAMES[id] || id}** (\`LICENSES/${id}.txt\`): ${areas.join(', ')}.`);
  }
  for (const f of plan.added.filter((x) => posix.dirname(x) !== '.' && !x.startsWith('LICENSES/') && LICENCE_FILE_NAMES.includes(posix.basename(x)))) {
    lines.push(`- \`${f}\`: the licence notice of the third-party files in \`${posix.dirname(f)}/\`, kept with them.`);
  }
  for (const f of plan.cfg.notices || []) lines.push(`- \`${f}\`: ${plan.cfg.why || 'licence notice listed in tools/bundle-app.config.json'}.`);
  return lines;
}

