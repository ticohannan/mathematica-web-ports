const BLOCK_RE = /<!-- bundle-contents:begin[\s\S]*?<!-- bundle-contents:end -->/;
/** The generated contents block currently in demos/<dir>/DESIGN.md, or null. */
export function designContentsBlock(dir, root = REPO_ROOT) {
  const f = path.join(root, 'demos', dir, 'DESIGN.md');
  if (!fs.existsSync(f)) return null;
  return fs.readFileSync(f, 'utf8').match(BLOCK_RE)?.[0] ?? null;
}
function updateDocs(dirs, root) {
  let changed = 0;
  for (const dir of dirs) {
    const f = path.join(root, 'demos', dir, 'DESIGN.md');
    const plan = planApp(dir, { root });
    if (plan.errors.length) { console.error(`${dir}: cannot plan the bundle:\n  ${plan.errors.join('\n  ')}`); process.exitCode = 1; continue; }
    const md = fs.readFileSync(f, 'utf8');
    if (!BLOCK_RE.test(md)) { console.error(`${dir}: DESIGN.md has no bundle-contents block (add the §6.1 subsection first)`); process.exitCode = 1; continue; }
    const next = md.replace(BLOCK_RE, contentsMarkdown(plan));
    if (next !== md) { fs.writeFileSync(f, next); changed++; console.log(`updated demos/${dir}/DESIGN.md`); }
  }
  console.log(`${changed} design document(s) changed`);
}

